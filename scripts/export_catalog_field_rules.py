#!/usr/bin/env python3
"""Generate the frontend's catalog field-rules contract.

The rules in ``backend/app/services/catalog/field_rules.py`` are authoritative.
This writes them as a TypeScript module that
``frontend/src/lib/catalog-field-rules.ts`` interprets, so the metadata editor,
the bulk-edit grid and the import remediation surfaces render the same
verdicts the server enforces. ``backend/tests/test_catalog_field_rules.py``
fails when the committed module no longer matches the rules.

Usage::

    python3 scripts/export_catalog_field_rules.py            # write the module
    python3 scripts/export_catalog_field_rules.py --check    # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BACKEND_ROOT = REPO_ROOT / "backend"
OUTPUT_PATH = REPO_ROOT / "frontend" / "src" / "lib" / "catalog-field-rules.generated.ts"

sys.path.insert(0, str(BACKEND_ROOT))

from app.services.catalog.field_rules import field_rules_contract  # noqa: E402


def render_module() -> str:
    contract = json.dumps(field_rules_contract(), indent=2, sort_keys=False)
    return (
        "// Generated by scripts/export_catalog_field_rules.py from\n"
        "// backend/app/services/catalog/field_rules.py. Do not edit by hand;\n"
        "// backend/tests/test_catalog_field_rules.py fails when this file is stale.\n"
        "//\n"
        "// The server enforces these rules on batches and import acceptance.\n"
        "// frontend/src/lib/catalog-field-rules.ts renders the same verdicts.\n"
        "\n"
        "export const CATALOG_FIELD_RULES = "
        + contract
        + " as const;\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed module differs")
    args = parser.parse_args(argv)
    rendered = render_module()
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != rendered:
            print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale; run scripts/export_catalog_field_rules.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} matches the catalog field rules")
        return 0
    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
