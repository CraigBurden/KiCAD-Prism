#!/usr/bin/env python3
"""Generate the frontend's role matrix from the caller policy.

``backend/app/core/policy.py`` is authoritative. This writes its
``role_matrix_contract()`` as a TypeScript module that
``frontend/src/lib/roles.ts`` reads to decide which controls to offer; the
server still authorizes every request. ``backend/tests/test_caller_policy.py``
fails when the committed module no longer matches the policy.

Usage::

    python3 scripts/export_role_matrix.py            # write the module
    python3 scripts/export_role_matrix.py --check    # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BACKEND_ROOT = REPO_ROOT / "backend"
OUTPUT_PATH = REPO_ROOT / "frontend" / "src" / "lib" / "role-matrix.generated.ts"

sys.path.insert(0, str(BACKEND_ROOT))

from app.core.policy import role_matrix_contract  # noqa: E402


def render_module() -> str:
    contract = json.dumps(role_matrix_contract(), indent=2, sort_keys=False)
    return (
        "// Generated by scripts/export_role_matrix.py from\n"
        "// backend/app/core/policy.py. Do not edit by hand;\n"
        "// backend/tests/test_caller_policy.py fails when this file is stale.\n"
        "//\n"
        "// The server authorizes every request. This matrix only decides which\n"
        "// controls the client offers.\n"
        "\n"
        "export const ROLE_MATRIX = "
        + contract
        + " as const;\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed module differs")
    args = parser.parse_args(argv)
    rendered = render_module()
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != rendered:
            print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale; run scripts/export_role_matrix.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} matches the caller policy")
        return 0
    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
