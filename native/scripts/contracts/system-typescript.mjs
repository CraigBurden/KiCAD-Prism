// TypeScript types for the System Builder v2 contracts, for the frontend.
//
//   node scripts/contracts/system-typescript.mjs           write the files
//   node scripts/contracts/system-typescript.mjs --check   fail when a file is stale
//
// Reads the generated JSON Schema (run build:prism-contracts first) and writes one module per
// root into frontend/src/features/system-builder/model/. Each module is self-contained, so a
// shared definition (an endpoint, a layout entry) appears in more than one; they are structural
// types, so the copies are interchangeable.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const native = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const schemaRoot = path.join(native, "contracts/generated/schema");
const outRoot = path.resolve(native, "../frontend/src/features/system-builder/model");
const check = process.argv.includes("--check");

const roots = [
  ["SystemV2.json", "SystemV2", "system-v2.generated.ts"],
  ["SystemOpsA0.json", "SystemOpsA0", "system-ops-a0.generated.ts"],
  ["SystemBundleA0.json", "SystemBundleA0", "system-bundle-a0.generated.ts"],
];

const banner = (file) =>
  `// Generated by native/scripts/contracts/system-typescript.mjs from\n` +
  `// native/contracts/generated/schema/${file}. Do not edit by hand;\n` +
  `// native-hygiene fails when this file is stale.\n`;

// A cross-schema reference names the other schema by its urn `$id` (import-document carries a
// whole SystemV2); resolve those to the generated files.
const byUrn = new Map();
for (const [file] of roots) {
  const { $id } = JSON.parse(await readFile(path.join(schemaRoot, file), "utf8"));
  byUrn.set($id, file);
}
const urnResolver = {
  order: 1,
  canRead: (ref) => ref.url.startsWith("urn:"),
  read: async (ref) => {
    const file = byUrn.get(ref.url.split("#")[0]);
    if (!file) throw new Error(`unknown schema ${ref.url}`);
    const { $id: _id, ...schema } = JSON.parse(await readFile(path.join(schemaRoot, file), "utf8"));
    return records(schema);
  },
};

// TypeSpec writes a Record as `unevaluatedProperties: {$ref}`, which json-schema-to-typescript
// ignores (it reads only `additionalProperties`); copy it across so a Record is an index type.
function records(node) {
  if (Array.isArray(node)) return node.map(records);
  if (!node || typeof node !== "object") return node;
  const out = Object.fromEntries(Object.entries(node).map(([key, value]) => [key, records(value)]));
  const extra = out.unevaluatedProperties;
  if (extra && typeof extra === "object" && !("not" in extra) && out.additionalProperties === undefined) {
    out.additionalProperties = extra;
    delete out.unevaluatedProperties;
  }
  return out;
}

const stale = [];
for (const [file, name, out] of roots) {
  // The urn `$id` is not a resolvable location; every reference is local (`#/$defs/...`).
  const { $id: _id, ...schema } = JSON.parse(await readFile(path.join(schemaRoot, file), "utf8"));
  const body = await compile(records(schema), name, {
    bannerComment: banner(file),
    cwd: schemaRoot,
    $refOptions: { resolve: { urn: urnResolver } },
    additionalProperties: false,
    unreachableDefinitions: false,
    format: true,
    style: { semi: true, singleQuote: false, printWidth: 120 },
  });
  const target = path.join(outRoot, out);
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== body) stale.push(path.relative(path.resolve(native, ".."), target));
  } else {
    await writeFile(target, body);
  }
}
if (stale.length) {
  console.error(`stale system TypeScript (run npm run build:system-typescript):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
